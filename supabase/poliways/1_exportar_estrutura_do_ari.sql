-- PASSO 1 — RODE NO SQL EDITOR DO PROJETO DO ARI (não altera nada, só lê).
--
-- Gera o script que recria a ESTRUTURA do banco (tabelas, funções, gatilhos,
-- segurança RLS, permissões, bucket de imagens) num projeto novo.
-- NÃO copia dados: nenhuma questão, aluno ou aula do Ari vai junto.
--
-- Como usar:
--   1. Rode este arquivo inteiro no SQL Editor do projeto do Ari.
--   2. O resultado é uma linha com a coluna "script". Clique na célula e use
--      "Copy cell content" (ou copie o valor inteiro).
--   3. Cole no SQL Editor do projeto NOVO (POLIWAYS) e rode.
--   4. Depois rode o 3_ajustes_poliways.sql no projeto novo.
-- =============================================================================

with
tabelas as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relacl
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
tipos as (
  select string_agg(
           format('do $t$ begin create type public.%I as enum (%s); exception when duplicate_object then null; end $t$;',
                  t.typname,
                  (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder)
                     from pg_enum e where e.enumtypid = t.oid)),
           E'\n' order by t.typname) as sql
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public' and t.typtype = 'e'
),
sequencias as (
  select string_agg(format('create sequence if not exists public.%I;', c.relname), E'\n' order by c.relname) as sql
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    -- sequências de colunas "identity" são criadas junto com a tabela
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
colunas as (
  select a.attrelid, a.attnum, a.attname,
         format_type(a.atttypid, a.atttypmod) as tipo,
         a.attnotnull, a.attidentity, a.attgenerated,
         pg_get_expr(ad.adbin, ad.adrelid) as expr
  from pg_attribute a
  join tabelas t on t.oid = a.attrelid
  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  where a.attnum > 0 and not a.attisdropped
),
criar_tabelas as (
  select string_agg(
           format(E'create table if not exists public.%I (\n%s\n);',
                  t.relname,
                  (select string_agg(
                            format('  %I %s%s%s%s',
                                   c.attname, c.tipo,
                                   case when c.attgenerated = 's' then format(' generated always as (%s) stored', c.expr) else '' end,
                                   case c.attidentity when 'a' then ' generated always as identity'
                                                      when 'd' then ' generated by default as identity' else '' end,
                                   case when c.attnotnull then ' not null' else '' end),
                            E',\n' order by c.attnum)
                     from colunas c where c.attrelid = t.oid)),
           E'\n\n' order by t.relname) as sql
  from tabelas t
),
padroes as (
  -- valores padrão entram depois das funções (alguns chamam funções próprias)
  select string_agg(format('alter table public.%I alter column %I set default %s;', t.relname, c.attname, c.expr),
                    E'\n' order by t.relname, c.attnum) as sql
  from colunas c join tabelas t on t.oid = c.attrelid
  where c.expr is not null and c.attgenerated = '' and c.attidentity = ''
),
funcoes as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.proname, p.oid) as sql
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
restricoes as (
  select string_agg(
           format('alter table public.%I add constraint %I %s;', t.relname, k.conname, pg_get_constraintdef(k.oid)),
           E'\n' order by case k.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'x' then 4 else 5 end,
                          t.relname, k.conname) as sql
  from pg_constraint k
  join tabelas t on t.oid = k.conrelid
  where k.contype in ('p', 'u', 'c', 'x', 'f')
),
indices as (
  select string_agg(replace(pg_get_indexdef(i.indexrelid), 'CREATE INDEX ', 'CREATE INDEX IF NOT EXISTS ')
                    || ';', E'\n' order by ic.relname) as sql
  from pg_index i
  join tabelas t on t.oid = i.indrelid
  join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
),
visoes as (
  select string_agg(
           format(E'create or replace view public.%I%s as\n%s',
                  c.relname,
                  case when c.reloptions is not null then format(' with (%s)', array_to_string(c.reloptions, ', ')) else '' end,
                  pg_get_viewdef(c.oid, true)),
           E'\n\n' order by c.relname) as sql
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
gatilhos as (
  select string_agg(
           format('drop trigger if exists %I on %s;', tg.tgname, tg.tgrelid::regclass) || E'\n' ||
           pg_get_triggerdef(tg.oid) || ';',
           E'\n' order by tg.tgrelid::regclass::text, tg.tgname) as sql
  from pg_trigger tg
  join pg_proc p on p.oid = tg.tgfoid
  join pg_namespace pn on pn.oid = p.pronamespace
  where not tg.tgisinternal
    and (tg.tgrelid in (select oid from tabelas)
         -- gatilho do cadastro (auth.users → profiles) usa função do schema public
         or (tg.tgrelid = 'auth.users'::regclass and pn.nspname = 'public'))
),
rls as (
  select string_agg(
           format('alter table public.%I enable row level security;', t.relname) ||
           case when t.relforcerowsecurity then format(E'\nalter table public.%I force row level security;', t.relname) else '' end,
           E'\n' order by t.relname) as sql
  from tabelas t
  where t.relrowsecurity
),
politicas as (
  select string_agg(
           format('drop policy if exists %I on %I.%I;', pol.policyname, pol.schemaname, pol.tablename) || E'\n' ||
           format('create policy %I on %I.%I as %s for %s to %s%s%s;',
                  pol.policyname, pol.schemaname, pol.tablename,
                  pol.permissive, pol.cmd,
                  (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ')
                     from unnest(pol.roles) as r),
                  case when pol.qual is not null then format(' using (%s)', pol.qual) else '' end,
                  case when pol.with_check is not null then format(' with check (%s)', pol.with_check) else '' end),
           E'\n' order by pol.schemaname, pol.tablename, pol.policyname) as sql
  from pg_policies pol
  where pol.schemaname = 'public'
     or (pol.schemaname = 'storage' and pol.tablename = 'objects')
),
grants_funcoes as (
  -- só funções cujas permissões foram alteradas (ex.: tiradas do público)
  select string_agg(
           format('revoke all on function %s from public, anon, authenticated;', p.oid::regprocedure) ||
           coalesce((select string_agg(
                              format(E'\ngrant execute on function %s to %s;',
                                     p.oid::regprocedure,
                                     case when acl.grantee = 0 then 'public' else quote_ident(r.rolname) end),
                              '')
                       from aclexplode(p.proacl) acl
                       left join pg_roles r on r.oid = acl.grantee
                       where acl.privilege_type = 'EXECUTE'
                         and (acl.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))), ''),
           E'\n' order by p.proname, p.oid) as sql
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p') and p.proacl is not null
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
grants_tabelas as (
  select string_agg(
           format('revoke all on table public.%I from anon, authenticated;', t.relname) ||
           coalesce((select string_agg(format(E'\ngrant %s on table public.%I to %I;', acl.privilege_type, t.relname, r.rolname), '')
                       from aclexplode(t.relacl) acl
                       join pg_roles r on r.oid = acl.grantee
                       where r.rolname in ('anon', 'authenticated')), ''),
           E'\n' order by t.relname) as sql
  from tabelas t
  where t.relacl is not null
),
grants_colunas as (
  select string_agg(format('grant %s (%I) on table public.%I to %I;', acl.privilege_type, a.attname, t.relname, r.rolname),
                    E'\n' order by t.relname, a.attnum) as sql
  from pg_attribute a
  join tabelas t on t.oid = a.attrelid
  cross join lateral aclexplode(a.attacl) acl
  join pg_roles r on r.oid = acl.grantee
  where a.attacl is not null and r.rolname in ('anon', 'authenticated')
),
realtime as (
  select string_agg(
           format('do $r$ begin alter publication supabase_realtime add table public.%I; exception when duplicate_object then null; end $r$;',
                  pt.tablename),
           E'\n' order by pt.tablename) as sql
  from pg_publication_tables pt
  where pt.pubname = 'supabase_realtime' and pt.schemaname = 'public'
),
buckets as (
  select string_agg(
           format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
                  b.id, b.name, case when b.public then 'true' else 'false' end,
                  coalesce(b.file_size_limit::text, 'null'),
                  coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null')),
           E'\n' order by b.id) as sql
  from storage.buckets b
),
extensoes as (
  select string_agg(format('--   %s', e.extname), E'\n' order by e.extname) as sql
  from pg_extension e
  where e.extname not in ('plpgsql', 'pgcrypto', 'uuid-ossp', 'pg_stat_statements', 'pg_graphql', 'supabase_vault', 'pgsodium', 'pgjwt')
)
select
  E'-- Estrutura exportada do projeto base em ' || to_char(now(), 'DD/MM/YYYY HH24:MI') || E'\n' ||
  E'-- Rode no projeto NOVO, inteiro, de uma vez.\n' ||
  E'set check_function_bodies = off;\n\n' ||
  coalesce(E'-- Extensões que o projeto base usa (ative em Database > Extensions se precisar):\n' || (select sql from extensoes) || E'\n\n', '') ||
  E'-- ===== Tipos =====\n'             || coalesce((select sql from tipos), '') || E'\n\n' ||
  E'-- ===== Sequências =====\n'        || coalesce((select sql from sequencias), '') || E'\n\n' ||
  E'-- ===== Tabelas =====\n'           || coalesce((select sql from criar_tabelas), '') || E'\n\n' ||
  E'-- ===== Funções =====\n'           || coalesce((select sql from funcoes), '') || E'\n\n' ||
  E'-- ===== Valores padrão =====\n'    || coalesce((select sql from padroes), '') || E'\n\n' ||
  E'-- ===== Chaves e restrições =====\n' || coalesce((select sql from restricoes), '') || E'\n\n' ||
  E'-- ===== Índices =====\n'           || coalesce((select sql from indices), '') || E'\n\n' ||
  E'-- ===== Visões =====\n'            || coalesce((select sql from visoes), '') || E'\n\n' ||
  E'-- ===== Gatilhos =====\n'          || coalesce((select sql from gatilhos), '') || E'\n\n' ||
  E'-- ===== Segurança (RLS) =====\n'   || coalesce((select sql from rls), '') || E'\n\n' ||
  E'-- ===== Políticas =====\n'         || coalesce((select sql from politicas), '') || E'\n\n' ||
  E'-- ===== Permissões =====\n'        || coalesce((select sql from grants_tabelas), '') || E'\n' ||
                                           coalesce((select sql from grants_colunas), '') || E'\n' ||
                                           coalesce((select sql from grants_funcoes), '') || E'\n\n' ||
  E'-- ===== Tempo real =====\n'        || coalesce((select sql from realtime), '') || E'\n\n' ||
  E'-- ===== Armazenamento (buckets) =====\n' || coalesce((select sql from buckets), '') || E'\n\n' ||
  E'notify pgrst, ''reload schema'';\n'
  as script;
